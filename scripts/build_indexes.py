#!/usr/bin/env python3
"""Build reproducible Markdown and JSON catalog exports from YAML."""
import argparse
import json
import sys
from catalog_common import ROOT, load_records


def clean(value):
    return str(value).replace("|", r"\|").replace("\n", " ").strip()


def md_table(title, headers, rows, intro):
    lines = [f"# {title}", "", intro, "", "| " + " | ".join(headers) + " |",
             "| " + " | ".join("---" for _ in headers) + " |"]
    for row in rows:
        lines.append("| " + " | ".join(clean(part) for part in row) + " |")
    return "\n".join(lines) + "\n"


def render_outputs():
    records = [record for _, record in load_records()]
    records.sort(key=lambda record: record["id"])
    components = [r for r in records if r["kind"] == "extension"]
    others = [r for r in records if r["kind"] != "extension"]
    intro = "Generated from `data/` by `scripts/build_indexes.py`. Do not edit this file manually."
    cockpit_rows = [
        (r["name"], r.get("group", ""), r.get("package_name") or "Not confirmed",
         f"[Source]({r['source_repo']})", r["summary"]) for r in components
    ]
    software_rows = [
        (r["name"], r["kind"], r["category"],
         f"[Project]({r.get('website') or r.get('source_repo')})", r["summary"])
        for r in others
    ]
    return {
        "generated/catalog.json": json.dumps(records, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        "generated/cockpit-plugins.md": md_table("Cockpit component catalog", ["Project", "Group", "Package (not availability-verified)", "Source", "Notes"], cockpit_rows, intro + f" {len(components)} entries; none were hardware or installation tested."),
        "generated/software-index.md": md_table("Linux distributions, images, software and resources", ["Project", "Kind", "Category", "Link", "Summary"], software_rows, intro)
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Fail when committed outputs are stale")
    args = parser.parse_args()
    stale = []
    for relative, content in render_outputs().items():
        path = ROOT / relative
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print("Wrote", relative)
    if stale:
        print("Stale generated files: " + ", ".join(stale), file=sys.stderr)
        print("Run: python scripts/build_indexes.py", file=sys.stderr)
        return 1
    if args.check:
        print("Generated catalog files are up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())

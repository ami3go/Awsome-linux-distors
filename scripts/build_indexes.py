#!/usr/bin/env python3
"""Render Awesome Linux catalog views from the authoritative YAML records."""
import argparse
import json
import sys
from catalog_common import ROOT, load_records

CATEGORIES = json.loads((ROOT / "schemas/categories.json").read_text(encoding="utf-8"))["categories"]


def safe(value):
    return str(value).replace("|", r"\|").replace("\n", " ").strip()


def item_link(record):
    return record.get("source_repo") or record["website"]


def description(record):
    text = " ".join(record["summary"].split()).rstrip(".")
    return text[:1].upper() + text[1:] + "."


def entry(record, extension=False):
    line = f"- [{record['name']}]({item_link(record)}) - {description(record)}"
    if extension:
        package = f"`{record['package_name']}`" if record.get("package_name") else "unconfirmed"
        line += f" *{record.get('group', 'standalone')}; package: {package}.*"
    return line


def table(title, headers, rows, intro):
    lines = [f"# {title}", "", intro, "",
             "| " + " | ".join(headers) + " |",
             "| " + " | ".join("---" for _ in headers) + " |"]
    for values in rows:
        lines.append("| " + " | ".join(safe(value) for value in values) + " |")
    return "\n".join(lines) + "\n"


def render_outputs():
    records = sorted((record for _, record in load_records()), key=lambda record: record["id"])
    components = [record for record in records if record["kind"] == "extension"]
    output = {
        "generated/catalog.json": json.dumps(records, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        "generated/software-index.md": table(
            "Linux catalog full index",
            ["Project", "Kind", "Category", "Status", "Upstream link", "Summary"],
            [[r["name"], r["kind"], r["category"], r["listing_status"], f"[Project]({item_link(r)})", r["summary"]] for r in records],
            "Complete source-linked record directory. Browse the [human-friendly categories](../README.md#contents) first. Generated by `scripts/build_indexes.py`.",
        ),
        "generated/cockpit-plugins.md": table(
            "Cockpit modules and extensions",
            ["Project", "Functional category", "Source group", "Package (unverified)", "Upstream link", "Notes"],
            [[r["name"], r["category"], r["group"], r.get("package_name") or "Not confirmed", f"[Source]({r['source_repo']})", r["summary"]] for r in components],
            "Historical research snapshot, **not** an endorsement or verified APT installation guide. Browse [Cockpit by purpose](../integrations/cockpit/README.md).",
        )
    }

    intro = ("Generated from the structured YAML catalog. Changes belong in `data/`, not in this page. "
             "**Highlighted** means editorial visibility, not installation, security or hardware validation.")
    cockpit = ("# Cockpit integration directory\n\n"
               "[Back to Awesome Linux Homelab](../../README.md) · "
               "[Original Cockpit research](../../archive/cockpit-research-2026-10-19.md)\n\n"
               "This is a **65-entry historical research catalog** organized by what each module does, "
               "rather than who publishes it. Package names are not proof of repository availability. "
               "No entries were installation-tested or hardware-qualified for this list.\n\n")
    for category in CATEGORIES:
        subset = [r for r in records if r["category"] == category["id"]]
        page = (f"# {category['title']}\n\n"
                "[Back to the Awesome Linux Homelab list](../README.md)\n\n"
                f"{category['description']}\n\n{intro}\n")
        for status, title in [
            ("highlighted", "Highlighted starting points"),
            ("research", "Research and alternatives"),
            ("legacy", "Legacy references"),
        ]:
            selected = sorted((r for r in subset if r["listing_status"] == status), key=lambda r: r["name"].lower())
            if selected:
                page += f"\n## {title}\n\n" + "\n".join(entry(r) for r in selected) + "\n"
        if any(r["kind"] == "extension" for r in subset):
            page += ("\nFor Cockpit integration and package caveats, see the "
                     "[Cockpit cross-index](../integrations/cockpit/README.md).\n")
        output[f"categories/{category['id']}.md"] = page

        components_here = sorted((r for r in components if r["category"] == category["id"]), key=lambda r: r["name"].lower())
        if components_here:
            cockpit += f"## {category['title']} ({len(components_here)})\n\n"
            cockpit += "\n".join(entry(r, extension=True) for r in components_here) + "\n\n"
    output["integrations/cockpit/README.md"] = cockpit
    return output


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Fail when committed outputs are stale")
    args = parser.parse_args()
    stale = []
    for relative, content in render_outputs().items():
        path = ROOT / relative
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print("Wrote", relative)
    if stale:
        print("Stale generated files: " + ", ".join(stale), file=sys.stderr)
        print("Run: python scripts/build_indexes.py", file=sys.stderr)
        return 1
    if args.check:
        print("Generated catalog files are up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
